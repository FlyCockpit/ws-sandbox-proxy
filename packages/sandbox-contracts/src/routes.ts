type ObjectSchema = z.ZodObject;

export type SdkRoute = {
  method: "get" | "post" | "delete" | "put";
  transport?: "upload" | "download";
  /** Request body is one binary chunk (uploads). */
  binary?: boolean;
  /** A binary chunk addressed by an `{offset}` path segment instead of Content-Range. */
  chunkOffsetInPath?: boolean;
  /** Success body is raw bytes (200 whole, 206 one range), not JSON. */
  binaryResponse?: boolean;
  idempotency?: boolean;
  successStatus?: 200 | 201 | 202;
  body?: z.ZodType;
  /** OpenAPI path template, e.g. `/v1/sandboxes/{id}`. */
  path: `/v1/${string}`;
  summary: string;
  /** Feature this route provides; null for discovery routes. */
  feature: SdkFeature | null;
  /** Scopes the calling key needs, all of them. Informational; the server enforces its own table. */
  scopes: readonly SdkScope[];
  params: ObjectSchema | null;
  query: ObjectSchema;
  /** Component name and schema of the 200 body. */
  response: { name: string; schema: z.ZodType };
  /** Error code for a missing or invisible resource on this route. */
  notFound: SdkErrorCode | null;
  paginated: boolean;
  /** Route-specific error codes beyond the common set (for example 410 expiry). */
  errors?: readonly SdkErrorCode[];
};

/**
 * Params schema of a mutation route, preserved per literal path so clients can
 * type it. Matches the runtime `path.includes("{id}")` branch below exactly: a
 * differently-named `{...}` segment types as no params, never as `{id}`.
 */
export type MutationParams<P extends `/v1/${string}`> = P extends `${string}{id}${string}`
  ? typeof resourceIdParamsSchema
  : null;

function mutation<P extends `/v1/${string}`, B extends z.ZodType>(
  path: P,
  feature: SdkFeature,
  scopes: readonly SdkScope[],
  body: B,
  notFound: SdkErrorCode | null = "sandbox.not_found",
  method: "post" | "delete" = "post",
) {
  return {
    method,
    path,
    feature,
    scopes,
    body,
    summary: "Accept an idempotent action; poll the operation location for its outcome.",
    params: (path.includes("{id}") ? resourceIdParamsSchema : null) as MutationParams<P>,
    query: emptyQuerySchema,
    response: { name: "MutationReceipt", schema: mutationReceiptSchema },
    notFound,
    paginated: false,
  } as const;
}

/**
 * THE `/v1` route registry. The server registers exactly these routes, the
 * OpenAPI document is generated from them, and `/v1/capabilities` reports
 * their features. Add a route here and the server fails to type-check until it
 * provides a handler.
 */
const processErrors = [
  "sandbox.process_not_found",
  "sandbox.process_stale",
  "sandbox.process_unknown_outcome",
  "sandbox.process_not_started",
  "sandbox.process_exited",
  "sandbox.process_cancel_pending",
  "sandbox.process_unavailable",
  "sandbox.process_stdin_closed",
  "UNSUPPORTED_CAPABILITY",
] as const;
function processMutation<B extends z.ZodType>(
  suffix: "signal" | "kill" | "stdin",
  feature: SdkFeature,
  scopes: readonly SdkScope[],
  body: B,
) {
  return {
    method: "post",
    path: `/v1/sandboxes/{id}/processes/{pid}/${suffix}`,
    feature,
    scopes,
    body,
    summary: "Accept a qualified tracked-command control; poll its receipt.",
    params: processParamsSchema,
    query: emptyQuerySchema,
    response: { name: "MutationReceipt", schema: mutationReceiptSchema },
    notFound: "sandbox.process_not_found",
    paginated: false,
    errors: processErrors,
  } as const;
}

