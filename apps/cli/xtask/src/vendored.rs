//! `cargo xtask vendored-russh` — keep `third_party/russh-0.65.2` honest and
//! upgradable (procedure: `third_party/README.md`).
//!
//! - `--check` proves the tree is the published russh 0.65.2 crate plus
//!   `third_party/russh-0.65.2.patch` and nothing else, and that the build
//!   really uses it. It takes the published `.crate` (cargo's registry cache
//!   when present, else <https://static.crates.io>), checks its SHA-256
//!   against the checksum the lockfile recorded for the registry crate
//!   before it was vendored, unpacks it in memory, applies the patch
//!   strictly (every context and removed line must match at its stated
//!   line; no fuzz) and compares the result with the vendored tree file by
//!   file, byte by byte. The only file the vendored tree may add is
//!   [`NOTICE`]. Then `Cargo.lock` must carry exactly one russh, at this
//!   version and from no registry, with no `[[patch.unused]]`, and the two
//!   manifests must pin and patch this version.
//! - `--advisories` reports what cargo-deny cannot: cargo-deny matches
//!   advisories only against crates with a registry source, and a path
//!   `[patch]` has none. It reads RustSec's `crates/russh/*.md` (a fresh
//!   download of the advisory database, or `--advisory-db <checkout>`) and
//!   fails on any advisory that affects this version and is not in
//!   `apps/cli/deny.toml` `[advisories] ignore`, or if crates.io yanked it.
//!   Malformed advisory or index metadata is an error, never a pass, and a
//!   prerelease `VERSION` is refused (see [`stable_version`]).
//! - `--update <version>` moves the vendored copy to another stable release:
//!   it fetches that crate (checksum from the crates.io index), re-applies
//!   the patch (hunks may move; any changed context line stops it) and
//!   computes the rewrites of the version, checksum and paths in
//!   [`REWRITTEN`], all in memory; then writes `third_party/russh-<version>`,
//!   its patch and the rewrites, runs `cargo update -p russh`, the wiring
//!   check and `sync-docs`, and only then deletes the old (verified) copy.
//!   A failure after the first write restores every file ([`Plan::commit`]).

use std::collections::BTreeMap;
use std::fs;
use std::io::Read;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail, ensure};
use sha2::{Digest, Sha256};

const NAME: &str = "russh";
const VERSION: &str = "0.65.2";
/// The checksum `Cargo.lock` recorded for `russh 0.65.2` from crates.io.
const CHECKSUM: &str = "78229f06e4d96d83bea5f5133ad3b6e4b5f0ce22d8e31c1ff7243ec8e18d5ba1";
/// The one file the vendored tree adds: the Apache-2.0 §4(b) notice.
const NOTICE: &str = "NOTICE-wssp.md";
/// RustSec's advisory database, as GitHub serves its default branch.
const ADVISORY_DB: &str = "https://github.com/rustsec/advisory-db/archive/refs/heads/main.tar.gz";
/// Files (from the repository root) whose mentions of the vendored version,
/// checksum and upstream commit `--update` rewrites. `apps/cli/AGENTS.md`'s
/// mirrors are regenerated by `sync-docs`.
const REWRITTEN: &[&str] = &[
    "Cargo.toml",
    "apps/cli/Cargo.toml",
    "apps/cli/xtask/src/vendored.rs",
    "apps/cli/xtask/src/main.rs",
    "apps/cli/AGENTS.md",
    "apps/cli/src/commands/sandbox/ssh/input.rs",
    "THIRD-PARTY-LICENSES.md",
    "third_party/README.md",
    "docs/design/connect-channel-contract.md",
    ".github/workflows/cli-ci.yml",
];

#[derive(Debug, clap::Args)]
pub struct Args {
    /// Verify the vendored tree against the published crate and the patch,
    /// and that the build uses it.
    #[arg(long)]
    check: bool,
    /// Fail on a RustSec advisory or a yank that affects the vendored
    /// version (cargo-deny skips path crates).
    #[arg(long)]
    advisories: bool,
    /// With `--advisories`: a local checkout of rustsec/advisory-db instead
    /// of a fresh download.
    #[arg(long, value_name = "DIR", requires = "advisories")]
    advisory_db: Option<PathBuf>,
    /// Move the vendored copy to this russh release (see
    /// `third_party/README.md`).
    #[arg(long, value_name = "VERSION")]
    update: Option<String>,
}

pub fn run(args: Args) -> Result<()> {
    let modes = [args.check, args.advisories, args.update.is_some()];
    ensure!(
        modes.iter().filter(|mode| **mode).count() == 1,
        "pass exactly one of `--check`, `--advisories` or `--update <version>` \
         (third_party/README.md)"
    );
    let root = repo_root();
    let current = Release {
        version: VERSION.to_owned(),
        checksum: CHECKSUM.to_owned(),
    };
    if args.check {
        verify(&root, &current)?;
        verify_wiring(&root, VERSION)?;
        println!(
            "third_party/{NAME}-{VERSION} is {NAME} {VERSION} ({CHECKSUM}) plus \
             third_party/{NAME}-{VERSION}.patch, and the build uses it"
        );
        Ok(())
    } else if args.advisories {
        advisories(&root, args.advisory_db.as_deref())
    } else {
        update(&root, &current, args.update.as_deref().unwrap_or_default())
    }
}

/// A published russh release: its version and its `.crate`'s SHA-256.
struct Release {
    version: String,
    checksum: String,
}

impl Release {
    fn dir(&self, root: &Path) -> PathBuf {
        root.join("third_party")
            .join(format!("{NAME}-{}", self.version))
    }

    fn patch(&self, root: &Path) -> PathBuf {
        root.join("third_party")
            .join(format!("{NAME}-{}.patch", self.version))
    }

    /// The crate's files, from bytes whose checksum is this release's.
    fn unpack(&self) -> Result<BTreeMap<String, Vec<u8>>> {
        let crate_bytes = published_crate(&self.version)?;
        let digest = hex(&Sha256::digest(&crate_bytes));
        ensure!(
            digest == self.checksum,
            "{NAME}-{}.crate has SHA-256 {digest}, not {}",
            self.version,
            self.checksum
        );
        unpack(&crate_bytes, &format!("{NAME}-{}/", self.version))
    }
}

/// The vendored tree is the crate plus its patch, plus [`NOTICE`].
fn verify(root: &Path, release: &Release) -> Result<()> {
    let mut expected = release.unpack()?;
    let patch_path = release.patch(root);
    let patch = fs::read_to_string(&patch_path)
        .with_context(|| format!("reading {}", patch_path.display()))?;
    apply(&mut expected, &parse_patch(&patch)?, Fit::Exact)?;
    let vendored = release.dir(root);
    let mut actual = read_tree(&vendored)?;
    ensure!(
        actual.remove(NOTICE).is_some(),
        "{} has no {NOTICE}",
        vendored.display()
    );
    compare(&expected, &actual)?;
    let pins_path = root.join(KEY_FIXTURES);
    let pins = fs::read_to_string(&pins_path)
        .with_context(|| format!("reading {}", pins_path.display()))?;
    check_pins(&pins, &release.version, &expected, &patch)
        .with_context(|| format!("{KEY_FIXTURES} does not pin the published crate's files"))
}

// ------------------------------------------------------- key-fixture pins

/// The one exception `pnpm policy:template-secrets`
/// (`scripts/check-template-secret-patterns.mjs`) makes to "never a private
/// key in git": a vendored upstream file holding russh's own test keys, while
/// its bytes hash to the pin here. Each line is `<sha256>  <repository path>`
/// (`sha256sum` format) of a file of the vendored tree; `--check` proves each
/// pin is the published crate's own bytes of that file, that the patch does
/// not touch it, and that it does hold a private-key header (a pin is never
/// spent on a file that needs none). `--update` re-pins the same files of the
/// new crate and drops (and names) any that moved, became patched or no
/// longer hold a key; a new pin is a hand edit that `--check` then proves.
const KEY_FIXTURES: &str = "third_party/russh-key-fixtures.sha256";

/// The pins of [`KEY_FIXTURES`], as paths below the vendored tree with their
/// SHA-256. Anything but sorted, unique, well-formed lines naming a file of
/// `third_party/russh-<version>/` is an error.
fn parse_pins(text: &str, version: &str) -> Result<Vec<(String, String)>> {
    let prefix = format!("third_party/{NAME}-{version}/");
    ensure!(
        text.is_empty() || text.ends_with('\n'),
        "the last line has no newline"
    );
    let mut pins: Vec<(String, String)> = Vec::new();
    for (number, line) in text.split_terminator('\n').enumerate() {
        let number = number + 1;
        let (digest, path) = line
            .split_once("  ")
            .with_context(|| format!("line {number} is not `<sha256>  <path>`"))?;
        ensure!(
            digest.len() == 64
                && digest
                    .bytes()
                    .all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f')),
            "line {number}: `{digest}` is not a lowercase SHA-256"
        );
        let file = path
            .strip_prefix(&prefix)
            .with_context(|| format!("line {number}: `{path}` is not below `{prefix}`"))?;
        // Plain path characters only, as the scanner demands: nothing a
        // tool could read as a delimiter, URL syntax or an escape.
        ensure!(
            file.split('/').all(|part| {
                !part.is_empty()
                    && part != "."
                    && part != ".."
                    && part
                        .bytes()
                        .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b'-'))
            }),
            "line {number}: `{path}` is not a plain relative path"
        );
        if let Some((previous, _)) = pins.last() {
            ensure!(
                previous.as_str() < file,
                "line {number}: `{path}` is out of order or repeated"
            );
        }
        pins.push((file.to_owned(), digest.to_owned()));
    }
    Ok(pins)
}

/// Every pin names an unpatched file of `crate_files` (the published crate,
/// after the patch) with exactly the pinned SHA-256 and a private-key header.
fn check_pins(
    text: &str,
    version: &str,
    crate_files: &BTreeMap<String, Vec<u8>>,
    patch: &str,
) -> Result<()> {
    let patched = parse_patch(patch)?;
    for (file, digest) in parse_pins(text, version)? {
        // Any patch line naming the file (a hunk, mode, rename or copy
        // header) fails closed, as in the scanner.
        ensure!(
            !patched.iter().any(|edit| edit.path == file)
                && !patch.lines().any(|line| line.contains(file.as_str())),
            "`{file}` is changed by the patch, so it is not upstream content"
        );
        let bytes = crate_files
            .get(&file)
            .with_context(|| format!("`{file}` is not in {NAME} {version}"))?;
        let actual = hex(&Sha256::digest(bytes));
        ensure!(
            actual == digest,
            "`{file}` is pinned as {digest}, but {NAME} {version} has {actual}"
        );
        ensure!(
            has_private_key_header(bytes),
            "`{file}` has no private-key header, so it needs no pin"
        );
    }
    Ok(())
}

/// [`KEY_FIXTURES`] for `version`: the files of `old` that are still in
/// `crate_files`, unpatched and holding a key, with their new SHA-256; and
/// the files dropped.
fn repin(
    old: &[(String, String)],
    version: &str,
    crate_files: &BTreeMap<String, Vec<u8>>,
    patched: &[FilePatch],
) -> (String, Vec<String>) {
    let mut text = String::new();
    let mut dropped = Vec::new();
    for (file, _) in old {
        match crate_files.get(file) {
            Some(bytes)
                if has_private_key_header(bytes)
                    && !patched.iter().any(|edit| &edit.path == file) =>
            {
                let digest = hex(&Sha256::digest(bytes));
                text.push_str(&format!("{digest}  third_party/{NAME}-{version}/{file}\n"));
            }
            _ => dropped.push(file.clone()),
        }
    }
    (text, dropped)
}

/// The scanner's private-key pattern, `-----BEGIN [A-Z ]*PRIVATE KEY-----`.
fn has_private_key_header(bytes: &[u8]) -> bool {
    const BEGIN: &[u8] = b"-----BEGIN ";
    const KEY: &[u8] = b"PRIVATE KEY";
    (0..bytes.len()).any(|start| {
        let Some(rest) = bytes[start..].strip_prefix(BEGIN) else {
            return false;
        };
        // `-` is outside `[A-Z ]`, so a match's `PRIVATE KEY` ends the run
        // of `[A-Z ]` after `BEGIN ` and `-----` follows it.
        let run = rest
            .iter()
            .take_while(|byte| byte.is_ascii_uppercase() || **byte == b' ')
            .count();
        rest[..run].ends_with(KEY) && rest[run..].starts_with(b"-----")
    })
}

fn verify_wiring(root: &Path, version: &str) -> Result<()> {
    let read =
        |path: &str| fs::read_to_string(root.join(path)).with_context(|| format!("reading {path}"));
    let problems = wiring_problems(
        &read("Cargo.lock")?,
        &read("Cargo.toml")?,
        &read("apps/cli/Cargo.toml")?,
        version,
    )?;
    ensure!(
        problems.is_empty(),
        "the build does not use third_party/{NAME}-{version}:\n  {}\n  (procedure: third_party/README.md)",
        problems.join("\n  ")
    );
    Ok(())
}

/// Why the build would not use the vendored copy: the lockfile's russh is
/// not exactly one path package at `version`, cargo recorded the patch as
/// unused, or a manifest pins or patches another version.
fn wiring_problems(
    lock: &str,
    root_manifest: &str,
    cli_manifest: &str,
    version: &str,
) -> Result<Vec<String>> {
    let lock: toml::Table = toml::from_str(lock).context("parsing Cargo.lock")?;
    let mut problems = Vec::new();
    let packages = lock
        .get("package")
        .and_then(toml::Value::as_array)
        .map(Vec::as_slice)
        .unwrap_or_default();
    let russh: Vec<_> = packages
        .iter()
        .filter(|package| package.get("name").and_then(toml::Value::as_str) == Some(NAME))
        .collect();
    if russh.len() != 1 {
        problems.push(format!(
            "Cargo.lock has {} `{NAME}` packages, not one",
            russh.len()
        ));
    }
    for package in &russh {
        let found = package
            .get("version")
            .and_then(toml::Value::as_str)
            .unwrap_or("?");
        if found != version {
            problems.push(format!("Cargo.lock has `{NAME}` {found}, not {version}"));
        }
        if let Some(source) = package.get("source").and_then(toml::Value::as_str) {
            problems.push(format!(
                "Cargo.lock takes `{NAME}` {found} from {source}, not the path patch"
            ));
        }
    }
    let unused = lock
        .get("patch")
        .and_then(|patch| patch.get("unused"))
        .and_then(toml::Value::as_array)
        .map(Vec::as_slice)
        .unwrap_or_default();
    for entry in unused {
        let name = entry
            .get("name")
            .and_then(toml::Value::as_str)
            .unwrap_or("?");
        let found = entry
            .get("version")
            .and_then(toml::Value::as_str)
            .unwrap_or("?");
        problems.push(format!(
            "Cargo.lock lists the patch `{name}` {found} under [[patch.unused]]"
        ));
    }
    problems.extend(manifest_problems(root_manifest, cli_manifest, version)?);
    Ok(problems)
}

/// Why the manifests would not use `third_party/russh-<version>`: the root
/// `[patch.crates-io]` or the CLI's `=` pin names another version.
fn manifest_problems(
    root_manifest: &str,
    cli_manifest: &str,
    version: &str,
) -> Result<Vec<String>> {
    let mut problems = Vec::new();
    let root_manifest: toml::Table = toml::from_str(root_manifest).context("parsing Cargo.toml")?;
    let patched = root_manifest
        .get("patch")
        .and_then(|patch| patch.get("crates-io"))
        .and_then(|registry| registry.get(NAME))
        .and_then(|entry| entry.get("path"))
        .and_then(toml::Value::as_str);
    let want = format!("third_party/{NAME}-{version}");
    if patched != Some(want.as_str()) {
        problems.push(format!(
            "Cargo.toml [patch.crates-io] {NAME} has path {patched:?}, not \"{want}\""
        ));
    }
    let cli_manifest: toml::Table =
        toml::from_str(cli_manifest).context("parsing apps/cli/Cargo.toml")?;
    let pinned = cli_manifest
        .get("dependencies")
        .and_then(|deps| deps.get(NAME))
        .and_then(|dep| dep.get("version"))
        .and_then(toml::Value::as_str);
    let want = format!("={version}");
    if pinned != Some(want.as_str()) {
        problems.push(format!(
            "apps/cli/Cargo.toml pins {NAME} at {pinned:?}, not \"{want}\""
        ));
    }
    Ok(problems)
}

/// The repository root (the xtask crate is `<root>/apps/cli/xtask`).
fn repo_root() -> PathBuf {
    let cli = crate::workspace_root();
    cli.parent()
        .and_then(Path::parent)
        .map_or(cli.clone(), Path::to_path_buf)
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

fn download(url: &str, limit: u64) -> Result<Vec<u8>> {
    let mut response = ureq::get(url)
        .call()
        .with_context(|| format!("downloading {url}"))?;
    response
        .body_mut()
        .with_config()
        .limit(limit)
        .read_to_vec()
        .with_context(|| format!("reading {url}"))
}

/// The `.crate` from cargo's registry cache, else from static.crates.io.
fn published_crate(version: &str) -> Result<Vec<u8>> {
    let file = format!("{NAME}-{version}.crate");
    let cargo_home = std::env::var_os("CARGO_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|home| PathBuf::from(home).join(".cargo")));
    if let Some(cache) = cargo_home.map(|home| home.join("registry").join("cache"))
        && let Ok(registries) = fs::read_dir(&cache)
    {
        for registry in registries.flatten() {
            let candidate = registry.path().join(&file);
            if let Ok(bytes) = fs::read(&candidate) {
                return Ok(bytes);
            }
        }
    }
    download(
        &format!("https://static.crates.io/crates/{NAME}/{file}"),
        16 * 1024 * 1024,
    )
}

/// What the crates.io index says about one release.
#[derive(Debug, PartialEq, Eq)]
struct IndexEntry {
    checksum: String,
    yanked: bool,
}

/// The entry for `version` in a sparse-index file (one JSON object a line).
/// Fails closed: a line that is not an object with a string `vers`, or the
/// entry without a string `cksum` and a boolean `yanked`, is an error.
fn index_entry(index: &str, version: &str) -> Result<IndexEntry> {
    for (number, line) in index.lines().enumerate() {
        if line.trim().is_empty() {
            continue;
        }
        let line_number = number + 1;
        let entry: serde_json::Value = serde_json::from_str(line)
            .with_context(|| format!("line {line_number} is not JSON"))?;
        let vers = entry
            .get("vers")
            .and_then(serde_json::Value::as_str)
            .with_context(|| format!("line {line_number} has no string `vers`"))?;
        if vers != version {
            continue;
        }
        let checksum = entry
            .get("cksum")
            .and_then(serde_json::Value::as_str)
            .with_context(|| {
                format!("{NAME} {version} (line {line_number}) has no string `cksum`")
            })?;
        let yanked = entry
            .get("yanked")
            .and_then(serde_json::Value::as_bool)
            .with_context(|| {
                format!("{NAME} {version} (line {line_number}) has no boolean `yanked`")
            })?;
        return Ok(IndexEntry {
            checksum: checksum.to_owned(),
            yanked,
        });
    }
    bail!("crates.io has no {NAME} {version}")
}

fn crates_io_entry(version: &str) -> Result<IndexEntry> {
    let url = format!(
        "https://index.crates.io/{}/{}/{NAME}",
        &NAME[..2],
        &NAME[2..4]
    );
    let index = download(&url, 16 * 1024 * 1024)?;
    index_entry(&String::from_utf8_lossy(&index), version)
        .with_context(|| format!("reading the crates.io index file {url}"))
}

/// A release version wssp may vendor or audit: wssp ships stable russh only.
/// For a version without a prerelease, `semver::VersionReq::matches` is
/// exactly cargo-deny's `is_affected` comparison (cargo-deny special-cases
/// only prerelease versions), so refusing prereleases keeps the two equal.
fn stable_version(version: &str) -> Result<semver::Version> {
    let parsed =
        semver::Version::parse(version).with_context(|| format!("`{version}` is not a version"))?;
    ensure!(
        parsed.pre.is_empty(),
        "{NAME} {version} is a prerelease; wssp vendors stable releases only"
    );
    Ok(parsed)
}

