/**
 * Statuses a route can return. Every authenticated route can see 401, 403
 * (scope/allowlist/inactive key), 409 (account deletion or a concurrent
 * change), 413 (oversize body), 415, 429, 500 and 503. 400 covers invalid path
 * or query input; 404 is present only on routes that address one resource.
 */
export function sdkRouteErrorStatuses(route: SdkRoute): number[] {
  const statuses = [400, 401, 403, 409, 413, 415, 429, 500, 503];
  if (route.notFound || route.method !== "get") statuses.push(404);
  for (const code of route.errors ?? []) {
    const status = SDK_ERRORS[code][0];
    if (!statuses.includes(status)) statuses.push(status);
  }
  return statuses.sort((a, b) => a - b);
}
