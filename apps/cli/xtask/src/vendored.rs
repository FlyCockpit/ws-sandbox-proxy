    /// A scratch repository with `russh-1.0.0` vendored.
    fn scratch_repo(label: &str) -> PathBuf {
        let root = std::env::temp_dir().join(format!(
            "wssp-xtask-{label}-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        for (path, text) in [
            ("third_party/russh-1.0.0/src/lib.rs", "pub fn old() {}\n"),
            ("third_party/russh-1.0.0/NOTICE-wssp.md", "russh 1.0.0\n"),
            ("third_party/russh-1.0.0.patch", "old patch\n"),
            (
                "Cargo.toml",
                "russh = { path = \"third_party/russh-1.0.0\" }\n",
            ),
            ("apps/cli/Cargo.toml", "russh = \"=1.0.0\"\n"),
            ("Cargo.lock", "russh 1.0.0\n"),
            ("apps/cli/CLAUDE.md", "mirror\n"),
        ] {
            let file = root.join(path);
            fs::create_dir_all(file.parent().unwrap()).unwrap();
            fs::write(file, text).unwrap();
        }
        root
    }

    fn scratch_plan(root: &Path) -> Plan {
        Plan {
            root: root.to_path_buf(),
            old: "1.0.0".to_owned(),
            new: "1.1.0".to_owned(),
            tree: tree(&[
                ("src/lib.rs", "pub fn new() {}\n"),
                (NOTICE, "russh 1.1.0\n"),
            ]),
            patch: "new patch\n".to_owned(),
            rewrites: vec![
                (
                    "Cargo.toml".to_owned(),
                    "russh = { path = \"third_party/russh-1.1.0\" }\n".to_owned(),
                ),
                (
                    "apps/cli/Cargo.toml".to_owned(),
                    "russh = \"=1.1.0\"\n".to_owned(),
                ),
            ],
        }
    }

