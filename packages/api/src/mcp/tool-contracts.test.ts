import { readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { SERVICE_ACTIONS, SERVICE_SCOPES } from "../lib/service-scopes";
import { MCP_TOOLS, visibleMcpTools } from "./tool-contracts";

const coveragePath = new URL("../../../../docs/mcp-tool-coverage.md", import.meta.url);
function coverage() {
  const exposed = new Set<string>(MCP_TOOLS.flatMap((tool) => [...tool.actions]));
  const rows = [
    ["Tool", "Required scopes", "Service actions"],
    ...MCP_TOOLS.map((tool) => [tool.name, tool.scopes.join(", "), tool.actions.join(", ")]),
  ];
  const widths = [0, 1, 2].map((column) => Math.max(...rows.map((row) => row[column]!.length)));
  const rowLine = (row: string[]) =>
    `| ${row.map((cell, column) => cell.padEnd(widths[column]!)).join(" | ")} |`;
  return [
    "# MCP tool coverage",
    "",
    "Generated by `packages/api/src/mcp/tool-contracts.test.ts`. Regenerate with `UPDATE_MCP_TOOL_COVERAGE=1 pnpm --filter @wssp/api test`.",
    "",
    rowLine(rows[0]!),
    rowLine(widths.map((width) => "-".repeat(width))),
    ...rows.slice(1).map(rowLine),
    "",
    "## Service actions without MCP tools",
    "",
    ...SERVICE_ACTIONS.filter((action) => !exposed.has(action)).map((action) => `- ${action}`),
    "",
  ].join("\n");
}
describe("MCP service boundary", () => {
  it("keeps the generated coverage document current", () => {
    const expected = coverage();
    if (process.env.UPDATE_MCP_TOOL_COVERAGE === "1") writeFileSync(coveragePath, expected);
    expect(readFileSync(coveragePath, "utf8")).toBe(expected);
  });
  it("maps every tool only to registered credential service actions", () => {
    expect(new Set(MCP_TOOLS.map((tool) => tool.name)).size).toBe(25);
    for (const tool of MCP_TOOLS)
      for (const action of tool.actions) expect(SERVICE_ACTIONS).toContain(action);
  });
  it("cannot reach person-only operations", () => {
    for (const tool of MCP_TOOLS) {
      expect(tool.actions.join(" ")).not.toMatch(
        /sdkKeys|agentTokens|mcpGrants|lower|raise|terminal|sandboxes\.connect|QueuedHost|queuedCommands\.(?:run|dismiss)/i,
      );
      expect(tool.name).not.toMatch(
        /token|grant|terminal|connect|shell|lower|raise|queue_(?:run|dismiss)/,
      );
      // CLI shells are a kind API plane: no tool needs or reaches them.
      expect(tool.scopes).not.toContain("sandboxes:connect");
      expect(tool.actions).not.toContain("sandboxes.connect");
    }
  });
  it("lists exactly the tools whose complete scope set is present", () => {
    expect(visibleMcpTools(new Set()).length).toBe(0);
    expect(visibleMcpTools(new Set(SERVICE_SCOPES))).toEqual(MCP_TOOLS);
    expect(visibleMcpTools(new Set(["commands:execute"])).map((tool) => tool.name)).toEqual([
      "command_start",
      "command_stdin",
    ]);
    expect(visibleMcpTools(new Set(["hosts:execute"])).map((tool) => tool.name)).toEqual([
      "host_command_run",
      "host_command_get",
      "host_command_cancel",
      "host_command_queue",
    ]);
  });
  it("keeps command and create refinements when the retry key is omitted", () => {
    const command = MCP_TOOLS.find((tool) => tool.name === "command_run")!;
    expect(command.input.safeParse({ id: "sandbox", script: "true", waitMs: 0 }).success).toBe(
      true,
    );
    expect(
      command.input.safeParse({ id: "sandbox", script: "true", argv: ["false"] }).success,
    ).toBe(false);
  });
});

it("dispatch imports only credential services and never person-only routers or operations", () => {
  const source = readFileSync(
    new URL("../../../../apps/server/src/mcp/tool-dispatch.ts", import.meta.url),
    "utf8",
  );
  expect(source).not.toMatch(/(?:from|import\()\s*["'][^"']*\/routers\//);
  expect(source).not.toMatch(
    /createRouterClient|liveOwnerSessionProcedure|protectedProcedure|publicProcedure|runQueuedHostCommand|dismissQueuedHostCommand|lowerAgentHostCommands|lowerHostTerminal|createAgentToken|revokeMcpGrant|getSelfKey|revokeSelfKey|self-key/,
  );
  const cases = [...source.matchAll(/case "([a-z_]+)":/g)].map((match) => match[1]);
  expect(cases.sort()).toEqual(MCP_TOOLS.map((tool) => tool.name).sort());
});
