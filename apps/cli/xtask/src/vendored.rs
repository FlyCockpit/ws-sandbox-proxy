// ------------------------------------------------------------------ patches

/// One file's edit in a unified diff (`git diff` format, paths `a/…` and
/// `b/…`, in place).
struct FilePatch {
    /// The `diff --git` line, if any.
    diff_line: Option<String>,
    path: String,
    hunks: Vec<Hunk>,
}

struct Hunk {
    /// The 0-based old start line the header states.
    old_start: usize,
    /// Whatever follows the closing `@@` (a function context).
    tail: String,
    /// Each body line: its mark (` `, `-`, `+`) and its text with `\n`.
    body: Vec<(u8, String)>,
}

impl Hunk {
    fn old_lines(&self) -> impl Iterator<Item = &str> {
        self.body
            .iter()
            .filter(|(mark, _)| *mark != b'+')
            .map(|(_, text)| text.as_str())
    }

    fn count(&self, skip: u8) -> usize {
        self.body.iter().filter(|(mark, _)| *mark != skip).count()
    }
}

fn parse_patch(patch: &str) -> Result<Vec<FilePatch>> {
    let mut patch_lines = patch.split_inclusive('\n').peekable();
    let mut files = Vec::new();
    let mut diff_line = None;
    // Only `diff --git`, `index`, `---`/`+++` and hunks: any other line (a
    // mode, rename, copy or binary header, or stray text) is refused, so
    // every change the patch makes is one this parser applies and checks.
    while let Some(line) = patch_lines.next() {
        if line.starts_with("diff --git ") {
            ensure!(
                diff_line.is_none(),
                "a `diff --git` block without `---`/`+++`: {}",
                line.trim_end()
            );
            diff_line = Some(line.to_owned());
            continue;
        }
        if diff_line.is_some() && line.starts_with("index ") {
            continue;
        }
        let Some(old_path) = line.strip_prefix("--- ") else {
            bail!("an unsupported patch line: {}", line.trim_end());
        };
        let new_line = patch_lines.next().context("a `---` without `+++`")?;
        let new_path = new_line
            .strip_prefix("+++ ")
            .context("a `---` without `+++`")?;
        let (old_path, new_path) = (old_path.trim_end(), new_path.trim_end());
        let path = new_path
            .strip_prefix("b/")
            .context("a new path without `b/`")?;
        ensure!(
            old_path.strip_prefix("a/") == Some(path),
            "only in-place edits are supported ({old_path} → {new_path})"
        );
        if let Some(diff) = &diff_line {
            ensure!(
                diff.trim_end() == format!("diff --git a/{path} b/{path}"),
                "`{}` does not name `{path}`",
                diff.trim_end()
            );
        }
        let mut hunks = Vec::new();
        while let Some(header) = patch_lines.next_if(|next| next.starts_with("@@ ")) {
            let (old_start, tail) = hunk_header(header)?;
            let mut body = Vec::new();
            while let Some(next) = patch_lines.peek() {
                match next.as_bytes().first() {
                    Some(mark @ (b' ' | b'-' | b'+')) => body.push((*mark, next[1..].to_owned())),
                    Some(b'\\') => bail!("{path}: `\\ No newline at end of file` is not supported"),
                    _ => break,
                }
                patch_lines.next();
            }
            hunks.push(Hunk {
                old_start,
                tail,
                body,
            });
        }
        files.push(FilePatch {
            diff_line: diff_line.take(),
            path: path.to_owned(),
            hunks,
        });
    }
    ensure!(
        diff_line.is_none(),
        "a `diff --git` block without `---`/`+++` at the end"
    );
    ensure!(!files.is_empty(), "the patch edits no file");
    Ok(files)
}

/// The 0-based old start line of a `@@ -l,c +l,c @@ tail` header, and the
/// tail.
fn hunk_header(header: &str) -> Result<(usize, String)> {
    let bad = || format!("a bad hunk header: {header}");
    let rest = header.strip_prefix("@@ -").with_context(bad)?;
    let old = rest.split([',', ' ']).next().with_context(bad)?;
    let line: usize = old.parse().with_context(bad)?;
    let tail = rest
        .split_once(" @@")
        .map(|(_, tail)| tail.trim_end_matches('\n').to_owned())
        .with_context(bad)?;
    Ok((line.saturating_sub(1), tail))
}

/// Split into lines, each keeping its `\n`.
fn lines(bytes: &[u8]) -> Vec<&[u8]> {
    bytes.split_inclusive(|byte| *byte == b'\n').collect()
}

/// Where a hunk may apply.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Fit {
    /// At its stated line only (`--check`).
    Exact,
    /// Its context and removed lines unchanged, at the nearest place at or
    /// after the previous hunk (`--update`: upstream moved code around it).
    Moved,
}

/// Apply `patch` to `files`; the hunks of a file must come in order. Returns
/// the patch with every hunk header restating where it applied.
fn apply(files: &mut BTreeMap<String, Vec<u8>>, patch: &[FilePatch], fit: Fit) -> Result<String> {
    let mut rendered = String::new();
    for file in patch {
        let path = &file.path;
        let original = files
            .get(path)
            .with_context(|| format!("the patch edits {path}, which the crate lacks"))?
            .clone();
        let old = lines(&original);
        let mut out: Vec<u8> = Vec::with_capacity(original.len());
        let mut copied = 0;
        let mut shift: isize = 0;
        let mut grown: isize = 0;
        if let Some(diff_line) = &file.diff_line {
            rendered.push_str(diff_line);
        }
        rendered.push_str(&format!("--- a/{path}\n+++ b/{path}\n"));
        for (number, hunk) in file.hunks.iter().enumerate() {
            let want: Vec<&str> = hunk.old_lines().collect();
            let fits = |at: usize| {
                at >= copied
                    && at + want.len() <= old.len()
                    && want
                        .iter()
                        .zip(&old[at..])
                        .all(|(line, found)| line.as_bytes() == *found)
            };
            let stated = hunk.old_start;
            let at = match fit {
                Fit::Exact => {
                    ensure!(stated >= copied, "{path}: hunks out of order");
                    if !fits(stated) {
                        let first = want
                            .iter()
                            .enumerate()
                            .find(|(offset, line)| {
                                old.get(stated + offset) != Some(&line.as_bytes())
                            })
                            .map_or(stated, |(offset, _)| stated + offset);
                        bail!("{path}: line {} does not match the patch", first + 1);
                    }
                    stated
                }
                Fit::Moved => {
                    let guess = stated.saturating_add_signed(shift).max(copied);
                    let nearest = (0..=old.len()).find_map(|distance| {
                        [guess.checked_add(distance), guess.checked_sub(distance)]
                            .into_iter()
                            .flatten()
                            .find(|at| fits(*at))
                    });
                    nearest.with_context(|| {
                        format!(
                            "{path}: hunk {} (`@@ -{} …`) no longer matches",
                            number + 1,
                            stated + 1
                        )
                    })?
                }
            };
            shift = at as isize - stated as isize;
            for kept in &old[copied..at] {
                out.extend_from_slice(kept);
            }
            for (mark, text) in &hunk.body {
                if *mark != b'-' {
                    out.extend_from_slice(text.as_bytes());
                }
            }
            copied = at + want.len();
            let (old_count, new_count) = (hunk.count(b'+'), hunk.count(b'-'));
            let new_start = (at as isize + grown) as usize;
            rendered.push_str(&format!(
                "@@ -{},{old_count} +{},{new_count} @@{}\n",
                at + 1,
                new_start + 1,
                hunk.tail
            ));
            for (mark, text) in &hunk.body {
                rendered.push(char::from(*mark));
                rendered.push_str(text);
            }
            grown += new_count as isize - old_count as isize;
        }
        for kept in old.get(copied..).unwrap_or_default() {
            out.extend_from_slice(kept);
        }
        files.insert(path.to_owned(), out);
    }
    Ok(rendered)
}

